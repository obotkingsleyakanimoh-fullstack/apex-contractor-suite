-- First-party, consent-based visitor and lead-intent analytics for Zitso Energy.
-- No IP address, name, email, phone number, or message content is stored here.

CREATE TABLE IF NOT EXISTS public.website_analytics_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visitor_id uuid NOT NULL,
  session_id uuid NOT NULL,
  event_name text NOT NULL CHECK (event_name IN (
    'page_view',
    'contact_form_start',
    'contact_form_submit',
    'quote_form_start',
    'quote_form_submit',
    'whatsapp_click',
    'phone_click',
    'email_click',
    'contact_cta_click',
    'quote_cta_click'
  )),
  page_path text NOT NULL CHECK (length(page_path) <= 500),
  page_title text CHECK (page_title IS NULL OR length(page_title) <= 200),
  traffic_source text NOT NULL DEFAULT 'direct' CHECK (length(traffic_source) <= 120),
  campaign text CHECK (campaign IS NULL OR length(campaign) <= 120),
  referrer_origin text CHECK (referrer_origin IS NULL OR length(referrer_origin) <= 255),
  target_label text CHECK (target_label IS NULL OR length(target_label) <= 100),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_website_analytics_created_at
  ON public.website_analytics_events (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_website_analytics_visitors
  ON public.website_analytics_events (visitor_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_website_analytics_sessions
  ON public.website_analytics_events (session_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_website_analytics_event_name
  ON public.website_analytics_events (event_name, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_website_analytics_source
  ON public.website_analytics_events (traffic_source, created_at DESC);

-- Keep event timestamps server-generated even if a public client sends a custom value.
CREATE OR REPLACE FUNCTION public.set_website_analytics_event_timestamp()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  NEW.created_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS t_website_analytics_event_timestamp ON public.website_analytics_events;
CREATE TRIGGER t_website_analytics_event_timestamp
  BEFORE INSERT ON public.website_analytics_events
  FOR EACH ROW EXECUTE FUNCTION public.set_website_analytics_event_timestamp();

ALTER TABLE public.website_analytics_events ENABLE ROW LEVEL SECURITY;
GRANT INSERT ON public.website_analytics_events TO anon, authenticated;
GRANT SELECT ON public.website_analytics_events TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.website_analytics_events_id_seq TO anon, authenticated;
GRANT ALL ON public.website_analytics_events TO service_role;

CREATE POLICY "public can submit anonymous analytics" ON public.website_analytics_events
  FOR INSERT TO anon, authenticated
  WITH CHECK (
    page_path NOT LIKE '/admin%'
    AND page_path <> '/auth'
  );

CREATE POLICY "staff can read analytics" ON public.website_analytics_events
  FOR SELECT TO authenticated
  USING (public.is_staff(auth.uid()));

CREATE OR REPLACE FUNCTION public.get_website_analytics_summary(p_days integer DEFAULT 30)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_days integer := GREATEST(1, LEAST(COALESCE(p_days, 30), 365));
  v_since timestamptz;
  v_result jsonb;
BEGIN
  IF NOT public.is_staff(auth.uid()) THEN
    RAISE EXCEPTION 'Not authorised to view website analytics';
  END IF;

  v_since := date_trunc('day', now()) - ((v_days - 1) * interval '1 day');

  SELECT jsonb_build_object(
    'page_views', COALESCE((
      SELECT count(*) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'page_view'
    ), 0),
    'contact_page_views', COALESCE((
      SELECT count(*) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'page_view' AND page_path = '/contact'
    ), 0),
    'quote_page_views', COALESCE((
      SELECT count(*) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'page_view' AND page_path = '/request-quote'
    ), 0),
    'contact_cta_clicks', COALESCE((
      SELECT count(*) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'contact_cta_click'
    ), 0),
    'quote_cta_clicks', COALESCE((
      SELECT count(*) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'quote_cta_click'
    ), 0),
    'unique_visitors', COALESCE((
      SELECT count(DISTINCT visitor_id) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'page_view'
    ), 0),
    'sessions', COALESCE((
      SELECT count(DISTINCT session_id) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'page_view'
    ), 0),
    'whatsapp_clicks', COALESCE((
      SELECT count(*) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'whatsapp_click'
    ), 0),
    'whatsapp_sessions', COALESCE((
      SELECT count(DISTINCT session_id) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'whatsapp_click'
    ), 0),
    'phone_clicks', COALESCE((
      SELECT count(*) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'phone_click'
    ), 0),
    'phone_sessions', COALESCE((
      SELECT count(DISTINCT session_id) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'phone_click'
    ), 0),
    'email_clicks', COALESCE((
      SELECT count(*) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'email_click'
    ), 0),
    'email_sessions', COALESCE((
      SELECT count(DISTINCT session_id) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'email_click'
    ), 0),
    'contact_form_starts', COALESCE((
      SELECT count(*) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'contact_form_start'
    ), 0),
    'contact_form_sessions', COALESCE((
      SELECT count(DISTINCT session_id) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'contact_form_start'
    ), 0),
    'quote_form_starts', COALESCE((
      SELECT count(*) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'quote_form_start'
    ), 0),
    'quote_form_sessions', COALESCE((
      SELECT count(DISTINCT session_id) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'quote_form_start'
    ), 0),
    'tracked_contact_submissions', COALESCE((
      SELECT count(*) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'contact_form_submit'
    ), 0),
    'tracked_quote_submissions', COALESCE((
      SELECT count(*) FROM public.website_analytics_events
      WHERE created_at >= v_since AND event_name = 'quote_form_submit'
    ), 0),
    'lead_intent_sessions', COALESCE((
      SELECT count(DISTINCT session_id) FROM public.website_analytics_events
      WHERE created_at >= v_since
        AND event_name IN (
          'contact_form_submit', 'quote_form_submit', 'whatsapp_click',
          'phone_click', 'email_click'
        )
    ), 0),
    'daily', COALESCE((
      SELECT jsonb_agg(
        jsonb_build_object(
          'date', to_char(days.day, 'YYYY-MM-DD'),
          'page_views', COALESCE(d.page_views, 0),
          'visitors', COALESCE(d.visitors, 0)
        ) ORDER BY days.day
      )
      FROM generate_series(
        date_trunc('day', now()) - ((v_days - 1) * interval '1 day'),
        date_trunc('day', now()),
        interval '1 day'
      ) AS days(day)
      LEFT JOIN LATERAL (
        SELECT
          count(*) FILTER (WHERE e.event_name = 'page_view') AS page_views,
          count(DISTINCT e.visitor_id) FILTER (WHERE e.event_name = 'page_view') AS visitors
        FROM public.website_analytics_events e
        WHERE e.created_at >= days.day
          AND e.created_at < days.day + interval '1 day'
      ) d ON TRUE
    ), '[]'::jsonb),
    'top_pages', COALESCE((
      SELECT jsonb_agg(jsonb_build_object('path', p.page_path, 'views', p.views) ORDER BY p.views DESC)
      FROM (
        SELECT page_path, count(*) AS views
        FROM public.website_analytics_events
        WHERE created_at >= v_since AND event_name = 'page_view'
        GROUP BY page_path
        ORDER BY views DESC
        LIMIT 8
      ) p
    ), '[]'::jsonb),
    'traffic_sources', COALESCE((
      SELECT jsonb_agg(jsonb_build_object('source', s.traffic_source, 'sessions', s.sessions) ORDER BY s.sessions DESC)
      FROM (
        SELECT COALESCE(NULLIF(traffic_source, ''), 'direct') AS traffic_source,
               count(DISTINCT session_id) AS sessions
        FROM public.website_analytics_events
        WHERE created_at >= v_since AND event_name = 'page_view'
        GROUP BY COALESCE(NULLIF(traffic_source, ''), 'direct')
        ORDER BY sessions DESC
        LIMIT 8
      ) s
    ), '[]'::jsonb)
  ) INTO v_result;

  RETURN v_result;
END;
$$;

REVOKE ALL ON FUNCTION public.get_website_analytics_summary(integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_website_analytics_summary(integer) TO authenticated;
